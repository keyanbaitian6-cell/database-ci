// Generate the identical live-page extractor used by PC pywebview and Android WebView.
// Its parser source is the iPhone viewer's already verified data.mjs.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const source = fileURLToPath(new URL('../web/pscube/data.mjs', import.meta.url));
const output = fileURLToPath(new URL('../assets/pscube_capture.js', import.meta.url));
const probe = fileURLToPath(new URL('../assets/pscube_auto_probe.js', import.meta.url));
const code = readFileSync(source, 'utf8').replace(/^export /gm, '');
if (/^\s*import\s/m.test(code) || /\bexport\b/.test(code)) throw new Error('The capture source needs a new bundling rule.');
writeFileSync(output, `/* Generated by tool/build_pscube_capture.mjs. Edit web/pscube/data.mjs. */\n` +
  `(async function () {\n${code}\n` +
  `try {\n` +
  `  const result = await capturePageWithNet({url: location.href, html: document.documentElement.outerHTML});\n` +
  `  return JSON.stringify({...result, source_url: location.href});\n` +
  `} catch (error) {\n` +
  `  return JSON.stringify({error: String(error?.message ?? error)});\n` +
  `}\n})()`);
// 自動取り込みの「今取り込めるか」の判定（読むだけ）。取り込み中の印 window.__pscubeBusy も返す。
writeFileSync(probe, `/* Generated by tool/build_pscube_capture.mjs. Edit web/pscube/data.mjs. */\n` +
  `(function () {\n${code}\n` +
  `try {\n` +
  `  return JSON.stringify({...autoPageState(location.href, document), busy: !!window.__pscubeBusy, url: location.href});\n` +
  `} catch (error) {\n` +
  `  return JSON.stringify({ready: false, reason: String(error?.message ?? error), busy: !!window.__pscubeBusy});\n` +
  `}\n})()`);
